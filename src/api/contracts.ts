import type { UserSettings } from '../game/sim/config'
import type { EndReason } from '../game/sim/types'

export const PAGE_SIZE = 10
export const MAX_PAGE_SIZE = 50

/** The options a match was played with. Ranking only compares equal configs. */
export type MatchConfig = UserSettings

export interface MatchRecord {
  matchId: string // generated by the client: also the idempotency key
  playerId: string
  playerName: string
  endedAt: string // ISO 8601
  score: number
  duration: number // effective seconds of active play
  reason: EndReason
  config: MatchConfig
}

export interface RankingEntry extends MatchRecord {
  rank: number // position in the whole ranking, not in the page
}

export interface Page<T> {
  items: T[]
  page: number
  pageSize: number
  total: number
  totalPages: number
}

export interface RankingParams extends MatchConfig {
  page: number
  pageSize: number
}

/** 201 when created, 200 when the matchId already existed (nothing duplicated). */
export interface SubmitMatchResponse {
  record: MatchRecord
  created: boolean
}

export interface ApiErrorBody {
  error: string
  message: string
  details?: string[]
}

export function isObject(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null
}

export function isMatchRecord(value: unknown): value is MatchRecord {
  if (!isObject(value)) return false
  const config = value.config
  return (
    typeof value.matchId === 'string' &&
    typeof value.playerId === 'string' &&
    typeof value.playerName === 'string' &&
    typeof value.endedAt === 'string' &&
    typeof value.score === 'number' &&
    typeof value.duration === 'number' &&
    (value.reason === 'time' || value.reason === 'death') &&
    isObject(config) &&
    typeof config.sessionDuration === 'number' &&
    typeof config.enemySpawnInterval === 'number'
  )
}

export function isPage(value: unknown): value is Page<unknown> {
  return (
    isObject(value) &&
    Array.isArray(value.items) &&
    typeof value.page === 'number' &&
    typeof value.totalPages === 'number' &&
    typeof value.total === 'number'
  )
}